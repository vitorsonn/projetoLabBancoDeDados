    private void carregarTabela() {
        List<Politico> lista = politicoDAO.getAllPoliticos();
        DefaultTableModel model = (DefaultTableModel) tblPoliticos.getModel();
        model.setNumRows(0);

        for (Politico p : lista) {
            model.addRow(new Object[]{
                p.getId(),
                p.getNome(),
                p.getPartido(),
                p.getCargo(),
                p.getCpf()
            });
        }
    }

    private void limparCampos() {
        txtId.setText("");
        txtNome.setText("");
        txtPartido.setText("");
        txtCPF.setText("");
        tblPoliticos.clearSelection();
        txtNome.requestFocus();
        if (cmbCargo.getItemCount() > 0) {
            cmbCargo.setSelectedIndex(0);
        }

    }

