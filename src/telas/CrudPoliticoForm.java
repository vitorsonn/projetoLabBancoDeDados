    private void btnSalvarPolitico1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSalvarPolitico1ActionPerformed
        if (txtNome.getText().trim().isEmpty() || txtPartido.getText().trim().isEmpty()
                || txtCPF.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Preencha todos os campos obrigatórios!");
            return;
        }

        Politico p = new Politico();
        p.setNome(txtNome.getText().trim());
        p.setPartido(txtPartido.getText().trim());
        p.setCargo((Cargo) cmbCargo.getSelectedItem());
        p.setCpf(txtCPF.getText().trim());

        if (txtId.getText().trim().isEmpty()) {
            if (politicoDAO.inserir(p)) {
                JOptionPane.showMessageDialog(this, "Político cadastrado com sucesso!");
            }
        } else {
            p.setId(Integer.parseInt(txtId.getText().trim()));
            politicoDAO.editar(p);
            JOptionPane.showMessageDialog(this, "Político atualizado com sucesso!");
        }

        limparCampos();
        carregarTabela();    }//GEN-LAST:event_btnSalvarPolitico1ActionPerformed

    private void btnExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExcluirActionPerformed
        if (txtId.getText().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Selecione um político na tabela para excluir.");
            return;
        }

        int confirm = JOptionPane.showConfirmDialog(this,
                "Deseja realmente excluir este político?", "Confirmação", JOptionPane.YES_NO_OPTION);

        if (confirm == JOptionPane.YES_OPTION) {
            int id = Integer.parseInt(txtId.getText());
            politicoDAO.excluir(id);
            limparCampos();
            carregarTabela();
        }
    }//GEN-LAST:event_btnExcluirActionPerformed

    private void btnLimparActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnLimparActionPerformed
        limparCampos();
    }//GEN-LAST:event_btnLimparActionPerformed

    private void tblPoliticosMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblPoliticosMouseClicked
        int linha = tblPoliticos.getSelectedRow();
        if (linha >= 0) {
            txtId.setText(tblPoliticos.getValueAt(linha, 0).toString());
            txtNome.setText(tblPoliticos.getValueAt(linha, 1).toString());
            txtPartido.setText(tblPoliticos.getValueAt(linha, 2).toString());
            cmbCargo.setSelectedItem(tblPoliticos.getValueAt(linha, 3));
            txtCPF.setText(tblPoliticos.getValueAt(linha, 4).toString());
        }
    }//GEN-LAST:event_tblPoliticosMouseClicked

