    private void btnSalvarDespesaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSalvarDespesaActionPerformed

        Politico politicoSelecionado = (Politico) jComboBox2.getSelectedItem();
        if (politicoSelecionado == null) {
            JOptionPane.showMessageDialog(this, "Selecione um político.");
            return;
        }

        if (despesaAtual.getItens().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Adicione pelo menos um item à despesa antes de salvar.");
            return;
        }

        LocalDate dataRegistro;
        try {
            dataRegistro = jdcData.getDate().toInstant()
                .atZone(ZoneId.systemDefault())
                .toLocalDate();
        } catch (DateTimeParseException ex) {
            JOptionPane.showMessageDialog(this, "Data inválida! Use o formato dd/MM/aaaa (ex: 12/11/2026).");
            return;
        }

        despesaAtual.setPolitico(politicoSelecionado);
        despesaAtual.setDescricao(txtDescricao.getText().trim());
        despesaAtual.setDataRegistro(dataRegistro);

        DespesaDAO dDAO = new DespesaDAO();
        if (dDAO.inserir(despesaAtual)) {
            JOptionPane.showMessageDialog(this, "Despesa salva com sucesso!");
            limparFormulario();
        } else {
            JOptionPane.showMessageDialog(this, "Erro ao salvar despesa no banco de dados.");
        }

    }//GEN-LAST:event_btnSalvarDespesaActionPerformed

    private void btnRemoverItemActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRemoverItemActionPerformed
        int linhaSelecionada = tblItens.getSelectedRow();
        if (linhaSelecionada < 0) {
            JOptionPane.showMessageDialog(this, "Selecione um item na tabela para remover.");
            return;
        }

        despesaAtual.removerItem(linhaSelecionada);
        atualizarTabelaItens();
    }//GEN-LAST:event_btnRemoverItemActionPerformed

    private void btnAddItemActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddItemActionPerformed
        ServicoRecurso servico = (ServicoRecurso) jComboBox1.getSelectedItem();
        if (servico == null) {
            JOptionPane.showMessageDialog(this, "Selecione um serviço/recurso.");
            return;
        }

        if (txbValor1.getText().trim().isEmpty() || txbValor.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Informe a quantidade e o valor unitário.");
            return;
        }

        try {
            int qtd = Integer.parseInt(txbValor1.getText().trim());
            if (qtd <= 0) {
                JOptionPane.showMessageDialog(this, "A quantidade deve ser maior que zero.");
                return;
            }

            String valorStr = txbValor.getText().replace("R$", "").replace(".", "").replace(",", ".").trim();
            BigDecimal valorUnit = new BigDecimal(valorStr);

            ItemDespesa item = new ItemDespesa(servico, qtd, valorUnit);
            despesaAtual.adicionarItem(item);

            atualizarTabelaItens();
            txbValor1.setText(""); // Limpa só a quantidade para facilitar o próximo item

        } catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(this, "Quantidade ou valor unitário inválido.");
        }

    }//GEN-LAST:event_btnAddItemActionPerformed

    private void limparFormulario() {
        despesaAtual = new Despesa();
        if (jComboBox2.getItemCount() > 0) {
            jComboBox2.setSelectedIndex(0);
        }
        if (jComboBox1.getItemCount() > 0) {
            jComboBox1.setSelectedIndex(0);
        }
        jdcData.setDate(java.sql.Date.valueOf(LocalDate.now()));        txtDescricao.setText("");
        txbValor1.setText("");
        preencherValorReferencia();
        atualizarTabelaItens();
    }

