    private void btnGerarComprovanteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGerarComprovanteActionPerformed
       int linhaSelecionada = tabelaDespesas.getSelectedRow();
        if (linhaSelecionada < 0) {
            JOptionPane.showMessageDialog(this,
                    "Selecione uma despesa na tabela para gerar o comprovante detalhado.",
                    "Aviso",
                    JOptionPane.WARNING_MESSAGE);
            return;
        }

        int idDespesa = (int) tabelaDespesas.getValueAt(linhaSelecionada, 0);
        DespesaDAO dDAO = new DespesaDAO();
        Despesa despesaCompleta = dDAO.getDespesa(idDespesa);

        if (despesaCompleta == null) {
            JOptionPane.showMessageDialog(this, "Não foi possível carregar os dados da despesa.");
            return;
        }

        JFileChooser fileChooser = new JFileChooser();
        fileChooser.setDialogTitle("Salvar Comprovante da Despesa #" + idDespesa);
        fileChooser.setSelectedFile(new File("comprovante_despesa_" + idDespesa + ".pdf"));

        if (fileChooser.showSaveDialog(this) == JFileChooser.APPROVE_OPTION) {
            try {
                String caminho = fileChooser.getSelectedFile().getAbsolutePath();
                if (!caminho.toLowerCase().endsWith(".pdf")) {
                    caminho += ".pdf";
                }

                config.PDFGenerator.gerarComprovanteDespesa(despesaCompleta, caminho);

                JOptionPane.showMessageDialog(this,
                        "Comprovante PDF gerado com sucesso em:\n" + caminho,
                        "Sucesso",
                        JOptionPane.INFORMATION_MESSAGE);

            } catch (Exception e) {
                JOptionPane.showMessageDialog(this,
                        "Erro ao gerar comprovante PDF: " + e.getMessage(),
                        "Erro",
                        JOptionPane.ERROR_MESSAGE);
            }
        }
    }//GEN-LAST:event_btnGerarComprovanteActionPerformed

