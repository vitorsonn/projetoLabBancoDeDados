  public static void exportarCSV(List<Despesa> lista, String caminhoArquivo) throws IOException {
        try (BufferedWriter writer = new BufferedWriter(new FileWriter(caminhoArquivo))) {
            writer.write("\uFEFF");
            writer.write("ID;Politico/Partido;Valor Total;Qtd Itens;Descricao;Data Registro\n");

            DateTimeFormatter fmt = DateTimeFormatter.ofPattern("dd/MM/yyyy");

            for (Despesa d : lista) {
                String dataStr = (d.getDataRegistro() != null) ? d.getDataRegistro().format(fmt) : "";
                String politicoStr = (d.getPolitico() != null) ? d.getPolitico().toString() : "";
                int qtdItens = (d.getItens() != null) ? d.getItens().size() : 0;

                String linha = String.format("%d;\"%s\";%s;%d;\"%s\";%s\n",
                        d.getId(),
                        politicoStr,
                        d.getValor() != null ? d.getValor().toString() : "0.00",
                        qtdItens,
                        d.getDescricao() != null ? d.getDescricao().replace("\n", " ") : "",
                        dataStr
                );

                writer.write(linha);
            }
        }
        
  }
  
