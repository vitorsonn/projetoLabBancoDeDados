    private List<Despesa> buscarDespesasFiltradas() {
        DespesaDAO dDAO = new DespesaDAO();
        Object selecionado = comboFiltroCategoria.getSelectedItem();

        if (selecionado instanceof Categoria) {
            return dDAO.getDespesasPorCategoria((Categoria) selecionado);
        }
        return dDAO.getAllDespesas();
    }

    public void preencherTabela() {
        List<Despesa> lista = buscarDespesasFiltradas();
        DefaultTableModel model = (DefaultTableModel) tabelaDespesas.getModel();
        model.setNumRows(0);

        DateTimeFormatter formatador = DateTimeFormatter.ofPattern("dd/MM/yyyy");
        java.text.NumberFormat fmtMoeda = java.text.NumberFormat.getCurrencyInstance(new java.util.Locale("pt", "BR"));

        BigDecimal total = BigDecimal.ZERO;

        for (Despesa d : lista) {
            String dataFormatada = (d.getDataRegistro() != null) ? d.getDataRegistro().format(formatador) : "";
            String politicoStr = (d.getPolitico() != null) ? d.getPolitico().toString() : "";
            int qtdItens = (d.getItens() != null) ? d.getItens().size() : 0;

            model.addRow(new Object[]{
                d.getId(),
                politicoStr,
                fmtMoeda.format(d.getValor()),
                qtdItens,
                dataFormatada
            });

            if (d.getValor() != null) {
                total = total.add(d.getValor());
            }
        }

        labelValorTotal.setText("Total Exibido: " + fmtMoeda.format(total));
    }
    
    

